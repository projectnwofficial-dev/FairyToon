        private static Dictionary<string, int> s_Index;
        private static Dictionary<string, int> Index
        {
            get
            {
                if (s_Index != null) return s_Index;
                s_Index = new Dictionary<string, int>(All.Length);
                for (int i = 0; i < All.Length; i++) s_Index[All[i].Name] = i;
                return s_Index;
            }
        }

        internal static bool TryGet(string name, out FairyToonPropertyEntry entry)
        { if (name != null && Index.TryGetValue(name, out int i)) { entry = All[i]; return true; } entry = default; return false; }

        internal static bool Belongs(PropertyBlock block, string name)
        { if (!TryGet(name, out var entry)) return false; for (int i = 0; i < entry.Blocks.Length; i++) if (entry.Blocks[i] == block) return true; return false; }

        internal static bool IsTexture(string name) => TryGet(name, out var entry) && entry.IsTexture;
    }
